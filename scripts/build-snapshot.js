const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

const root = path.resolve(__dirname, '..');

async function main() {
  const { normalizeSnapshot, validateSnapshot } = await import(pathToFileURL(path.join(root, 'src', 'schema.mjs')).href);
  const { mergeProviderPayload } = await import(pathToFileURL(path.join(root, 'src', 'provider-merge.mjs')).href);
  const seed = JSON.parse(fs.readFileSync(path.join(root, 'data', 'seed.json'), 'utf8'));
  let candidate = normalizeSnapshot({ ...seed, generatedAt: new Date().toISOString() });
  const mergeStats = [];

  const providerDir = path.join(root, 'data', 'imports', 'providers');
  if (fs.existsSync(providerDir)) {
    const files = fs.readdirSync(providerDir)
      .filter((name) => name.endsWith('.json') && !name.endsWith('.candidate.json'))
      .sort();
    for (const file of files) {
      const payload = JSON.parse(fs.readFileSync(path.join(providerDir, file), 'utf8'));
      const result = mergeProviderPayload(candidate, payload);
      candidate = result.snapshot;
      mergeStats.push({ file, ...result.stats });
    }
  }

  candidate = normalizeSnapshot({ ...candidate, generatedAt: new Date().toISOString() });
  const validation = validateSnapshot(candidate);
  if (!validation.ok) throw new Error(`Snapshot validation failed:\n- ${validation.errors.join('\n- ')}`);

  const snapshotDir = path.join(root, 'data', 'snapshots');
  fs.mkdirSync(snapshotDir, { recursive: true });
  const staged = path.join(snapshotDir, 'candidate.json');
  const live = path.join(snapshotDir, 'current.json');
  const prior = fs.existsSync(live) ? JSON.parse(fs.readFileSync(live, 'utf8')) : null;

  if (prior) {
    const normalizedPrior = normalizeSnapshot(prior);
    fs.writeFileSync(
      path.join(root, 'src', 'fallback-snapshot.mjs'),
      `// Generated last-known-good snapshot.\nexport const fallbackSnapshot = ${JSON.stringify(normalizedPrior, null, 2)};\n`
    );
  }

  fs.writeFileSync(staged, JSON.stringify(candidate, null, 2) + '\n');
  fs.renameSync(staged, live);
  fs.writeFileSync(
    path.join(root, 'src', 'snapshot.mjs'),
    `// Generated by scripts/build-snapshot.js. Do not edit manually.\nexport const snapshot = ${JSON.stringify(candidate, null, 2)};\n`
  );

  console.log(JSON.stringify({
    published: candidate.titles.length,
    schemaVersion: candidate.schemaVersion,
    providerMerges: mergeStats,
    live
  }));
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
